#!/usr/bin/env python3
"""
sync_n8n_from_repo.py — Push corrected workflow node definitions from the repo
into the LIVE n8n Postgres DB, updating BOTH copies in place (by workflow name).

CRITICAL (n8n 2.x, confirmed against workflow_history/workflow_published_version):
Every workflow has TWO copies in the DB:
  * workflow_entity.nodes            -> the DRAFT (what the editor displays)
  * workflow_history.nodes           -> the EXECUTABLE copy that an ACTIVE
                                        workflow actually runs, selected via
                                        workflow_entity.activeVersionId and/or
                                        workflow_published_version.publishedVersionId.
Updating only workflow_entity makes the editor look fixed while the live bot
keeps executing the OLD nodes. So this script updates BOTH, keeping versionId
pointers intact (no new version minted), so a plain `docker compose restart n8n`
reloads the corrected executable copy.

Usage (on the server, from the repo root):
    python3 scripts/sync_n8n_from_repo.py workflows/live > n8n_sync.sql
    N8N_DB=$(docker compose exec -T n8n printenv DB_POSTGRESDB_DATABASE)
    docker compose exec -T postgres bash -lc "export PGPASSWORD=\$POSTGRES_PASSWORD; \
        psql -U \$POSTGRES_USER -d $N8N_DB -v ON_ERROR_STOP=1" < n8n_sync.sql
    docker compose restart n8n

Only workflows whose top-level "name" matches a row in workflow_entity are updated.
"""
import json
import sys
import os

# Which workflow files carry fixes we want synced to live n8n.
TARGETS = [
    "Workflow 2 - AI Brain.json",
    "03 - Memory & Context Builder.json",
    "Workflow 7 - Handoff Tool.json",
    "08 - AI Output Processor.json",
]


def load(path):
    with open(path, "r", encoding="utf-8-sig") as f:  # utf-8-sig strips any BOM
        return json.load(f)


def dollar_quote(s):
    # Postgres dollar-quoting avoids all single-quote escaping problems.
    # Tag is chosen to never appear inside n8n JSON.
    tag = "n8sync"
    assert ("$" + tag + "$") not in s, "dollar-quote tag collision"
    return "$" + tag + "$" + s + "$" + tag + "$"


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "workflows/live"
    print("-- Auto-generated by scripts/sync_n8n_from_repo.py")
    print("-- Updates BOTH the draft (workflow_entity) and the executable copy")
    print("-- (workflow_history for the active/published version), in place, by name.")
    print("\\set ON_ERROR_STOP on")
    print("BEGIN;")
    updated = 0
    for fn in TARGETS:
        path = os.path.join(base, fn)
        if not os.path.exists(path):
            print(f"\\echo SKIP (missing): {fn}")
            continue
        d = load(path)
        name = d.get("name")
        nodes = d.get("nodes")
        conns = d.get("connections", {})
        if not name or nodes is None:
            print(f"\\echo SKIP (no name/nodes): {fn}")
            continue
        nodes_json = json.dumps(nodes, separators=(",", ":"))
        conns_json = json.dumps(conns, separators=(",", ":"))
        name_lit = dollar_quote(name)

        print(f"\\echo -> {name}")

        # 1) DRAFT copy (workflow_entity) — what the editor shows.
        print(
            "UPDATE workflow_entity "
            f"SET nodes = {dollar_quote(nodes_json)}::json, "
            f"connections = {dollar_quote(conns_json)}::json, "
            '"updatedAt" = NOW() '
            f"WHERE name = {name_lit};"
        )

        # 2) EXECUTABLE copy (workflow_history) — the row an ACTIVE workflow runs.
        #    Match the active version and the published version by versionId so we
        #    update exactly the rows that execute, without repointing anything.
        hist_where = (
            'h."workflowId" = (SELECT id FROM workflow_entity WHERE name = '
            f"{name_lit}) "
            "AND ("
            'h."versionId" = (SELECT "activeVersionId" FROM workflow_entity WHERE name = '
            f"{name_lit}) "
            "OR "
            'h."versionId" = (SELECT "publishedVersionId" FROM workflow_published_version '
            f'WHERE "workflowId" = (SELECT id FROM workflow_entity WHERE name = {name_lit}))'
            ")"
        )
        print(
            "UPDATE workflow_history h "
            f"SET nodes = {dollar_quote(nodes_json)}::json, "
            f"connections = {dollar_quote(conns_json)}::json, "
            '"updatedAt" = NOW() '
            f"WHERE {hist_where};"
        )
        updated += 1
    print("COMMIT;")
    print(f"\\echo Done. {updated} workflow(s) processed (draft + executable).")
    if updated == 0:
        print("\\echo WARNING: nothing matched — check workflow names.")


if __name__ == "__main__":
    main()


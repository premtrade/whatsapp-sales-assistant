#!/usr/bin/env python3
"""
sync_n8n_from_repo.py — Push corrected workflow node definitions from the repo
into the LIVE n8n Postgres DB, updating BOTH copies in place (by workflow name),
and REMAPPING credential IDs to the ones that exist on THIS n8n instance.

THREE things this handles (all confirmed causes of "synced but bot still broken"):

1) n8n 2.x keeps TWO copies of every workflow:
     workflow_entity.nodes  -> DRAFT (what the editor shows)
     workflow_history.nodes -> EXECUTABLE copy an ACTIVE workflow runs, selected
                               via workflow_entity.activeVersionId /
                               workflow_published_version.publishedVersionId.
   Updating only workflow_entity makes the editor look fixed while live
   executions keep running the OLD nodes. So we update BOTH, in place, keeping
   versionId pointers intact -> a plain `docker compose restart n8n` reloads the
   corrected executable copy.

2) Credential IDs are per-n8n-instance. The repo JSON references credential ids
   from the environment it was exported from; those ids DO NOT exist on your
   server, so writing nodes verbatim makes every DB/LLM node fail with
   "Credential with ID ... does not exist". So before writing, we REMAP each
   hardcoded credential id to the live id from credentials_entity, matched by
   (type, name) with a fallback to any credential of that type.

3) Idempotent: the remap only fires when the old id is actually present (guarded
   by a LIKE test), so re-running is safe.

Usage (on the server, from the repo root):
    python3 scripts/sync_n8n_from_repo.py workflows/live > n8n_sync.sql
    N8N_DB=$(docker compose exec -T n8n printenv DB_POSTGRESDB_DATABASE)
    docker compose exec -T postgres bash -lc "export PGPASSWORD=\$POSTGRES_PASSWORD; \
        psql -U \$POSTGRES_USER -d $N8N_DB -v ON_ERROR_STOP=1" < n8n_sync.sql
    docker compose restart n8n
"""
import json
import sys
import os

# Which workflow files carry fixes we want synced to live n8n.
TARGETS = [
    "01 - Incoming WhatsApp Message.json",
    "Workflow 2 - AI Brain.json",
    "03 - Memory & Context Builder.json",
    "Workflow 7 - Handoff Tool.json",
    "08 - AI Output Processor.json",
]


def load(path):
    with open(path, "r", encoding="utf-8-sig") as f:  # utf-8-sig strips any BOM
        return json.load(f)


def dollar_quote(s):
    # Postgres dollar-quoting avoids all single-quote escaping problems.
    # Tag is chosen to never appear inside n8n JSON.
    tag = "n8sync"
    assert ("$" + tag + "$") not in s, "dollar-quote tag collision"
    return "$" + tag + "$" + s + "$" + tag + "$"


def collect_credentials(d):
    """Return list of (type, old_id, name) referenced by this workflow's nodes."""
    out = []
    seen = set()
    for n in (d.get("nodes") or []):
        for ctype, val in (n.get("credentials") or {}).items():
            if isinstance(val, dict) and val.get("id"):
                key = (ctype, val["id"])
                if key not in seen:
                    seen.add(key)
                    out.append((ctype, val["id"], val.get("name") or ""))
    return out


def live_cred_lookup(ctype, name):
    """SQL expression that resolves THIS instance's credential id for a type.

    Prefer an exact (type, name) match, else fall back to the oldest credential
    of that type. Wrapped in COALESCE so a missing name match still resolves.
    """
    name = (name or "").replace("'", "''")
    return (
        "COALESCE("
        f"(SELECT id FROM credentials_entity WHERE type = '{ctype}' AND name = '{name}' "
        'ORDER BY "createdAt" LIMIT 1), '
        f"(SELECT id FROM credentials_entity WHERE type = '{ctype}' "
        'ORDER BY "createdAt" LIMIT 1))'
    )


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "workflows/live"
    print("-- Auto-generated by scripts/sync_n8n_from_repo.py")
    print("-- Updates DRAFT (workflow_entity) + EXECUTABLE (workflow_history) copies")
    print("-- in place by name, and REMAPS credential ids to this instance's ids.")
    print("\\set ON_ERROR_STOP on")
    print("BEGIN;")

    print("\\echo === Live credentials on this instance (type | id | name) ===")
    print("SELECT type, id, name FROM credentials_entity ORDER BY type, name;")

    updated = 0
    for fn in TARGETS:
        path = os.path.join(base, fn)
        if not os.path.exists(path):
            print(f"\\echo SKIP (missing): {fn}")
            continue
        d = load(path)
        name = d.get("name")
        nodes = d.get("nodes")
        conns = d.get("connections", {})
        if not name or nodes is None:
            print(f"\\echo SKIP (no name/nodes): {fn}")
            continue
        nodes_json = json.dumps(nodes, separators=(",", ":"))
        conns_json = json.dumps(conns, separators=(",", ":"))
        name_lit = dollar_quote(name)
        creds = collect_credentials(d)

        print(f"\\echo -> {name}")

        # 1) Write DRAFT copy (workflow_entity).
        print(
            "UPDATE workflow_entity "
            f"SET nodes = {dollar_quote(nodes_json)}::json, "
            f"connections = {dollar_quote(conns_json)}::json, "
            '"updatedAt" = NOW() '
            f"WHERE name = {name_lit};"
        )

        # 2) Write EXECUTABLE copy (workflow_history) for the active/published version.
        # Update every stored version, not just the selected active/published one.
        # n8n can keep stale executable versions alive; updating all of them
        # prevents a published-but-older version from masking the repo content.
        hist_where = (
            'h."workflowId" = (SELECT id FROM workflow_entity WHERE name = '
            f"{name_lit}) "
        )
        print(
            "UPDATE workflow_history h "
            f"SET nodes = {dollar_quote(nodes_json)}::json, "
            f"connections = {dollar_quote(conns_json)}::json, "
            '"updatedAt" = NOW() '
            f"WHERE {hist_where};"
        )

        # 3) REMAP credential ids to this instance's ids (both copies).
        for (ctype, old_id, cname) in creds:
            old_lit = dollar_quote(old_id)
            lookup = live_cred_lookup(ctype, cname)
            print(f"\\echo    remap {ctype} {old_id} -> live")
            print(
                "UPDATE workflow_entity "
                f"SET nodes = replace(nodes::text, {old_lit}, {lookup})::json "
                f"WHERE name = {name_lit} AND nodes::text LIKE '%' || {old_lit} || '%';"
            )
            print(
                "UPDATE workflow_history h "
                f"SET nodes = replace(nodes::text, {old_lit}, {lookup})::json "
                f"WHERE {hist_where} AND nodes::text LIKE '%' || {old_lit} || '%';"
            )
        updated += 1
    print("COMMIT;")
    print(f"\\echo Done. {updated} workflow(s) processed (draft + executable + cred remap).")
    if updated == 0:
        print("\\echo WARNING: nothing matched — check workflow names.")


if __name__ == "__main__":
    main()

